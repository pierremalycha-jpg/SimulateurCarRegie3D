import { createRequire } from 'module';
const require = createRequire('/opt/node22/lib/node_modules/');
const { chromium } = require('playwright');
import fs from 'fs';
const OUT = '/tmp/claude-0/-home-user/c77888a1-6f04-5876-a000-ab7e7f493575/scratchpad/shots';
const html = '<!doctype html><html lang="fr"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover"></head><body>' + fs.readFileSync('dist/index.html', 'utf8') + '</body></html>';
const three = fs.readFileSync('node_modules/three/build/three.module.min.js');
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 400, height: 820 }, deviceScaleFactor: 1, hasTouch: true, isMobile: true });
page.on('pageerror', (e) => console.log('PAGEERROR: ' + e.message));
await page.route('https://cdn.jsdelivr.net/**', (r) => r.fulfill({ body: three, contentType: 'application/javascript' }));
await page.route('https://fonts.googleapis.com/**', (r) => r.fulfill({ body: '', contentType: 'text/css' }));
await page.route('https://fonts.gstatic.com/**', (r) => r.abort());
await page.route('http://local.test/?lite', (r) => r.fulfill({ body: html, contentType: 'text/html' }));
await page.goto('http://local.test/?lite');
await page.waitForFunction(() => window.__dbg, null, { timeout: 30000 });
await page.waitForTimeout(1500);
await page.screenshot({ path: OUT + '/m1-start.png' });
const sw = await page.evaluate(() => [document.documentElement.scrollWidth, document.querySelector('#start').scrollWidth]);
console.log('scrollWidth', sw);
await page.evaluate(() => window.__dbg.start('standard', 'jour', 'basse', false));
await page.waitForTimeout(3000);
await page.screenshot({ path: OUT + '/m2-fps.png' });
await page.evaluate(() => { window.__dbg.teleport(1); window.__dbg.openStation('melangeur'); });
await page.waitForTimeout(3000);
await page.screenshot({ path: OUT + '/m3-mixer.png' });
await page.evaluate(() => { window.__dbg.closeStation(); window.__dbg.openPlan(); });
await page.waitForTimeout(3000);
await page.screenshot({ path: OUT + '/m4-plan.png' });
await browser.close();
